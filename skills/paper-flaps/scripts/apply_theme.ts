#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const USAGE = `Put the theme of one art style into a page: fonts, design tokens, signature rules, icons.

Usage: apply_theme.ts <index.html> <style>    replace the theme block of the page
       apply_theme.ts --list                   list the styles
       apply_theme.ts --self-test              apply every style to the template in memory

The theme lives in assets/themes/<style>.css. Its header names the Google Fonts URL and
the icon set ("phosphor <weight>" or "lucide <stroke width>"). The script writes the fonts
link between <!-- theme-fonts --> markers and a <style id="theme"> block between
<!-- theme --> markers. Running it twice gives the same page.
`;

const SKILL = path.dirname(import.meta.dirname);
const THEMES = path.join(SKILL, "assets/themes");
const ICONS = path.join(SKILL, "assets/icons");
const ROLES: Record<string, [string, string]> = { // interface role -> [phosphor name, lucide name]
  prev: ["caret-left", "chevron-left"],
  next: ["caret-right", "chevron-right"],
  down: ["arrow-down", "arrow-down"],
  out: ["arrow-up-right", "arrow-up-right"],
};
const PHOSPHOR_WEIGHTS = new Set(["thin", "light", "regular", "bold", "fill", "duotone"]);

class Fail extends Error {}

function fail(msg: string): never {
  throw new Fail("apply_theme: " + msg);
}

// Like Python's read_text: strict UTF-8, keeps a BOM, universal newlines.
function readText(p: string): string {
  const text = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(fs.readFileSync(p));
  return text.replace(/\r\n?/g, "\n");
}

function header(css: string, key: string): string {
  const m = css.match(new RegExp("^\\s*" + key + ":\\s*(.+?)\\s*$", "m"));
  if (!m) fail(`theme header has no '${key}:' line`);
  return m[1];
}

function iconSvg(lib: string, arg: string, role: string): string {
  let svg: string;
  if (lib === "phosphor") {
    if (!PHOSPHOR_WEIGHTS.has(arg)) fail(`unknown phosphor weight '${arg}'`);
    svg = readText(path.join(ICONS, "phosphor", arg, ROLES[role][0] + ".svg"));
    svg = svg.replaceAll('fill="currentColor"', 'fill="#000"');
  } else if (lib === "lucide") {
    if (arg.trim() === "" || Number.isNaN(Number(arg))) throw new Error(`could not convert string to float: '${arg}'`);
    svg = readText(path.join(ICONS, "lucide", ROLES[role][1] + ".svg"));
    svg = svg.replace(/<!--[\s\S]*?-->/g, "");
    svg = svg.replace(/\s(class|width|height)="[^"]*"/g, "");
    svg = svg.replaceAll('stroke="currentColor"', 'stroke="#000"');
    svg = svg.replace(/stroke-width="[^"]*"/g, () => `stroke-width="${arg}"`);
  } else {
    fail(`unknown icon library '${lib}'`);
  }
  return svg.replace(/\s+/g, " ").trim();
}

// urllib.parse.quote(svg, safe=" =:/,;'"): percent-encode UTF-8 bytes, uppercase hex.
function dataUri(svg: string): string {
  const safe = /[A-Za-z0-9_.~\- =:/,;']/;
  let out = "";
  for (const byte of Buffer.from(svg, "utf8")) {
    const ch = String.fromCharCode(byte);
    out += byte < 128 && safe.test(ch) ? ch : "%" + byte.toString(16).toUpperCase().padStart(2, "0");
  }
  return 'url("data:image/svg+xml,' + out + '")';
}

function fontsOf(css: string): string {
  const fonts = header(css, "fonts");
  if (!fonts.startsWith("https://fonts.googleapis.com/")) fail("fonts must come from fonts.googleapis.com");
  // Google Fonts answers 400 when a family with n axes has an entry with fewer than n values.
  for (const [, name, axes, entries] of fonts.matchAll(/family=([^:&]+):([a-zA-Z,]+)@([^&]+)/g)) {
    const n = axes.split(",").length;
    if (entries.split(";").some(e => e.split(",").length !== n)) {
      fail(`fonts: every entry of ${name} needs ${n} values (${axes})`);
    }
  }
  return fonts;
}

function build(style: string): [string, string] {
  const file = path.resolve(THEMES, `${style}.css`);
  if (!fs.statSync(file, { throwIfNoEntry: false })?.isFile()) {
    fail(`no theme '${style}'. Styles: ${styles().join(", ")}`);
  }
  const css = readText(file);
  const fonts = fontsOf(css);
  const parts = header(css, "icons").split(/\s+/);
  if (parts.length !== 2) throw new Error(`icons header needs two values, got ${parts.length}`);
  const [lib, arg] = parts;
  const icons = ":root {\n" + Object.keys(ROLES).map(r => `  --i-${r}: ${dataUri(iconSvg(lib, arg, r))};\n`).join("") + "}\n";
  const block = `<style id="theme" data-style="${style}">\n`
    + `/* Generated by scripts/apply_theme.ts from assets/themes/${style}.css. Edit the theme file, not this block. */\n`
    + `${icons}${css.trim()}\n</style>`;
  const link = `<link rel="stylesheet" href="${fonts}">`;
  return [link, block];
}

function replaceBetween(page: string, name: string, content: string): string {
  const pat = new RegExp(`(<!-- ${name} -->)[\\s\\S]*?(<!-- /${name} -->)`);
  if (!pat.test(page)) fail(`page has no <!-- ${name} --> … <!-- /${name} --> markers`);
  return page.replace(pat, (_m, open, close) => open + "\n" + content + "\n" + close);
}

function apply(page: string, style: string): string {
  const [link, block] = build(style);
  return replaceBetween(replaceBetween(page, "theme-fonts", link), "theme", block);
}

function styles(): string[] {
  return fs.readdirSync(THEMES).filter(f => f.endsWith(".css")).map(f => f.slice(0, -4)).sort();
}

function assert(ok: unknown, msg: string): void {
  if (!ok) throw new Error("AssertionError: " + msg);
}

function throwsFail(fn: () => unknown): boolean {
  try {
    fn();
  } catch (e) {
    if (e instanceof Fail) return true;
    throw e;
  }
  return false;
}

function selfTest(): void {
  const template = readText(path.join(SKILL, "assets/template.html"));
  for (const s of styles()) {
    const out = apply(template, s);
    assert(out === apply(out, s), `${s}: not idempotent`);
    assert(out.includes(`data-style="${s}"`), s);
    assert(out.split("--i-").length - 1 >= 4 + 4, `${s}: icon variables missing`);
    assert(!out.split('<style id="theme"')[1].split("</style>")[0].includes("currentColor"), `${s}: icon colour left in`);
  }
  const bad = readText(path.join(THEMES, "gouache-poster.css"))
    .replace(/(fonts: \S+)/, () => "fonts: https://fonts.googleapis.com/css2?family=X:opsz,wght@8..60,400;600");
  assert(throwsFail(() => fontsOf(bad)), "broken font axes passed");
  assert(throwsFail(() => apply(template, "no-such-style")), "unknown style passed");
  console.log(`apply_theme self-test: ${styles().length} styles ok`);
}

// pathlib's str(): drops "." parts and repeated slashes, keeps "..".
function pathlibStr(p: string): string {
  const parts = p.split("/").filter(s => s !== "" && s !== ".");
  return (p.startsWith("/") ? "/" : "") + parts.join("/") || ".";
}

function main(a: string[]): number {
  try {
    if (a.length === 1 && a[0] === "--list") {
      console.log(styles().join("\n"));
    } else if (a.length === 1 && a[0] === "--self-test") {
      selfTest();
    } else if (a.length === 2) {
      fs.writeFileSync(a[0], apply(readText(a[0]), a[1]), "utf8");
      console.log(`theme ${a[1]} -> ${pathlibStr(a[0])}`);
    } else {
      fail(USAGE);
    }
  } catch (e) {
    if (!(e instanceof Fail)) throw e;
    process.stderr.write(e.message + "\n");
    return 1;
  }
  return 0;
}

process.exitCode = main(process.argv.slice(2));
